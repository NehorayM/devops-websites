#!/usr/bin/env bash
# Writes supabase_all.sql: every backend file in run order, for one paste into the Supabase SQL Editor.
# Re-run after gen_duel_v2.py (a bank change rebuilds the duel answer key).
set -euo pipefail
cd "$(dirname "$0")/.."
{ echo "-- Ship It: every backend file in run order. Generated by tools/sql_all.sh; edit the source files, not this."
  echo "-- Paste into Supabase dashboard -> SQL Editor -> New query, and Run once. Safe to re-run."
  for f in supabase_setup.sql supabase_add_username.sql supabase_casino.sql supabase_casino_v2.sql supabase_duel.sql \
           supabase_duel_v2.sql supabase_exam_history.sql supabase_leaderboard.sql supabase_tournament.sql; do
    echo; echo "-- ======== $f ========"; cat "$f"; done; } > supabase_all.sql
echo "supabase_all.sql: $(wc -c < supabase_all.sql) bytes"
